import io

FS = "{0:c}".format(92)
X = chr(0x00d7)  # U+00D7 乘号


def patch(path, pairs):
    s = io.open(path, encoding="utf-8").read()
    for old, new in pairs:
        n = s.count(old)
        assert n == 1, (path, n, old[:80])
        s = s.replace(old, new)
    io.open(path, "w", encoding="utf-8").write(s)
    print("已更新", path, "共", len(pairs), "处")


